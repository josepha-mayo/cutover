"""Portable local Bob handoff for one freshly executed, blocked contract."""
import hashlib
import io
import json
import zipfile
from pathlib import Path

from .engine import digest, validate_contract, validate_plan


ROOT = Path(__file__).resolve().parents[1]
SOURCES = (
    'LICENSE', 'configure_bob.py', 'mcp_server.py', 'requirements-mcp.txt',
    'cutover/__init__.py', 'cutover/__main__.py', 'cutover/audit_report.py',
    'cutover/bundle.py', 'cutover/engine.py', 'cutover/reporting.py',
    'cutover/selected_replay.py', 'cutover/service.py', 'cutover/worker.py',
)


def render_repair_workspace(report, contract):
    """Caller must obtain this report through fresh independent execution."""
    validate_contract(contract)
    validate_plan(report['plan'])
    if report['status'] != 'blocked':
        raise ValueError('Prepare a repair workspace from a blocked rehearsal')
    if digest(contract) != report['contract_hash'] or digest(report['plan']) != report['plan_hash']:
        raise ValueError('Repair workspace inputs do not match the executed report')
    files = {name: (ROOT / name).read_bytes() for name in SOURCES}
    if hashlib.sha256(files['cutover/engine.py'].replace(b'\r\n', b'\n')).hexdigest() != report['engine_sha256']:
        raise ValueError('Repair workspace evaluator differs from the executed report')
    for case in ('parcel', 'contacts'):
        for name in ('contract', 'rename', 'backfill', 'late_bridge'):
            path = f'examples/{case}/{name}.json'
            files[path] = (ROOT / path).read_bytes()
    def put(name, value):
        files[name] = (json.dumps(value, ensure_ascii=True, indent=2) + '\n').encode()
    put('contract.json', contract)
    put('baseline-plan.json', report['plan'])
    put('baseline-report.json', report)
    files['.bob/custom_modes.yaml'] = b'''customModes:
  - slug: cutover-local-repair
    name: Cutover local repair
    roleDefinition: >-
      Repair the supplied SQLite rollout using Cutover MCP tools and measured evidence.
      Read TASK.md and contract.json. Preserve the contract, seeds, oracle and evaluator.
      Supply the complete contract on every custom tool call. Retain failed attempts.
      Save your candidate to work/bob-candidate.json and report bounded coverage honestly.
    groups:
      - read
      - edit
      - command
      - mcp
'''
    files['.bobignore'] = b'.venv/\n.git/\n'
    files['TASK.md'] = (
        '# Repair this failed handover in IBM Bob IDE\n\n'
        'Read contract.json, baseline-plan.json and baseline-report.json. '
        'Call inspect_imported_contract with the complete contract, then '
        'rehearse_candidate with case="custom", that same contract, and your five SQL plan fields. '
        'Use actual tool outcomes to diagnose and repair the failure. '
        'Never change the fixed contract, records, payloads, schedules, oracle or evaluator. '
        'Keep failed attempts. Save the final five-field plan to work/bob-candidate.json '
        'and reasoning to work/bob-repair.md. Retain the actual IDE task summary and history.\n\n'
        f'Observed baseline: {report["passed"]}/{report["total"]} probes passed; blocked.\n'
        f'Contract SHA-256: {report["contract_hash"]}\n'
        f'Plan SHA-256: {report["plan_hash"]}\n\n'
        'This handoff was generated by Cutover, not by Bob. Downloading or configuring '
        'it does not establish Bob usage or a successful repair. A pass is limited to '
        'these synthetic SQLite contracts and executed schedules.\n'
    ).encode()
    files['README.md'] = b'''# Local Bob repair workspace

Extract this ZIP into a new folder. Use synthetic data in the hosted demo;
run Cutover locally for private schemas. This archive contains your selected
blocked inputs and a fixed evaluator, not bundled passing reference repairs.
Inspect the source before running it. No API keys or account information are included.

1. With Python 3.10+ available, run `python verify_workspace.py`.
2. Create a local environment: `python -m venv .venv`.
3. Install the pinned MCP SDK using that environment's Python:
   `.venv/Scripts/python.exe -m pip install -r requirements-mcp.txt` on Windows,
   or `.venv/bin/python -m pip install -r requirements-mcp.txt` on Linux/macOS.
4. Run that Python with `configure_bob.py`. It creates absolute local paths in
   `.bob/mcp.json`; all MCP auto-approval permissions remain empty.
5. Open the extracted folder in Bob IDE. Review its trust/configuration prompts,
   confirm the Cutover MCP connection, choose Cutover local repair, and submit TASK.md.
6. Independently check the saved result:
   `python verify_workspace.py --candidate work/bob-candidate.json`.
   Exit 0 means this suite passed, 1 means blocked, and other errors remain unverified.
   Each attempt retains its report and Markdown in a new folder under work/. Import the candidate into
   the browser to compare it and, on a pass, export a separately verified PR gate kit.

Hashes detect changes against this package's inventory, not publisher authenticity.
Deliberately replacing the inventory defeats that check. Bob IDE access is separate;
the archive does not invoke Bob, purchase credits, or claim Bob authored a candidate.
'''
    files['verify_workspace.py'] = b'''"""Check packaged fixed inputs before independently executing a candidate."""
import argparse, hashlib, json, subprocess, sys, uuid
from pathlib import Path
root = Path(__file__).resolve().parent
parser = argparse.ArgumentParser()
parser.add_argument('--candidate', type=Path)
args = parser.parse_args()
try:
    manifest = json.loads((root/'WORKSPACE_MANIFEST.json').read_text(encoding='utf-8'))
    for name, expected in manifest['files'].items():
        if hashlib.sha256((root/name).read_bytes()).hexdigest() != expected:
            raise ValueError('Packaged fixed file changed: ' + name)
    print('Packaged fixed inputs match the recorded inventory.')
    if args.candidate:
        candidate = args.candidate.resolve()
        output = root/'work'/('verification-' + uuid.uuid4().hex)
        output.mkdir(parents=True)
        print('Evidence directory: ' + str(output), flush=True)
        result = subprocess.run([sys.executable, '-m', 'cutover', '--contract',
            str(root/'contract.json'), '--plan', str(candidate), '--output',
            str(output/'report.json'), '--markdown',
            str(output/'review.md')], cwd=root, timeout=120)
        sys.exit(result.returncode)
except (OSError, ValueError, KeyError, subprocess.TimeoutExpired) as exc:
    print('UNVERIFIED: ' + str(exc), file=sys.stderr)
    sys.exit(2)
'''
    manifest = {
        'kind': 'Cutover-generated local Bob repair handoff; not Bob usage evidence',
        'contract_hash': report['contract_hash'], 'plan_hash': report['plan_hash'],
        'engine_sha256': report['engine_sha256'], 'suite_hash': report['suite_hash'],
        'files': {name: hashlib.sha256(data).hexdigest() for name, data in files.items()},
    }
    put('WORKSPACE_MANIFEST.json', manifest)
    out = io.BytesIO()
    with zipfile.ZipFile(out, 'w', compression=zipfile.ZIP_DEFLATED) as archive:
        for name, data in files.items():
            archive.writestr(name, data)
    return out.getvalue()
